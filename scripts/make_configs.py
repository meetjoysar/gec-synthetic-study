"""Generate configs/experiments/*.yaml for the trimmed experiment grid.

Writing these from one script keeps the grid internally consistent: every E1
noise point, every E2 clean ratio and every E3/E4 condition is derived from the
same lists rather than hand-copied 12 times.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path("configs/experiments")
ROOT.mkdir(parents=True, exist_ok=True)

HEADER = "# Generated by scripts/make_configs.py - edit that, not this file.\n"

# Trimmed grid (deviations D4-D6, user-approved ~8 h GPU budget).
E1_PS = [0.1, 0.2, 0.4, 0.6]
# Extra arm (deviation D10): pre-compensated generator weights at p=0.2.
E1_PRECOMP_P = 0.2
E2_CLEAN = [0.0, 0.2, 0.33, 0.5]


def write(name: str, body: str) -> None:
    (ROOT / f"{name}.yaml").write_text(HEADER + body, encoding="utf-8", newline="\n")
    print(f"  wrote configs/experiments/{name}.yaml")


# --- E0: copy baseline, no training ---------------------------------------- #
write(
    "e0_copy",
    """
name: e0_copy
family: e0
condition: copy
description: >
  Copy baseline: the prediction IS the source. No training, no GPU.
  BLEU looks high while F0.5 is 0, which is the critique of using BLEU for GEC
  (Koo et al. 2023). ERRANT reports P=1.0 here because it defines
  p = tp/(tp+fp) if fp else 1.0 for an empty hypothesis set.
dataset:
  synthetic:
    enabled: false
  real:
    enabled: false
eval:
  splits: [val, test, indian]
keep_checkpoint: false
""".lstrip(),
)

# --- E1: noise-ratio sweep, synthetic-only, clean_ratio = 0 ---------------- #
for p in E1_PS:
    write(
        f"e1_p{p}",
        f"""
name: e1_p{p}
family: e1
condition: synthetic
description: >
  Noise-ratio sweep (spec E1): synthetic-only training at p={p},
  clean_ratio=0. Selection is on val F0.5 only.
dataset:
  synthetic:
    enabled: true
    p: {p}
    clean_ratio: 0.0
  real:
    enabled: false
eval:
  splits: [val, test]
keep_checkpoint: false
""".lstrip(),
    )

# --- E2: clean:noisy mix at the best p from E1 ----------------------------- #
for c in E2_CLEAN:
    if c == 0.0:
        # Spec section 7: "0.0 = the E1 run; reuse it". alias_of makes
        # run_experiments write a pointer instead of repeating the training.
        write(
            "e2_clean0.0",
            """
name: e2_clean0.0
family: e2
condition: synthetic
description: >
  clean_ratio=0.0 is by definition the best E1 run (spec E2 says to reuse it).
  This config is an alias: run_experiments writes a metrics.json pointing at
  the E1 run, so no model is retrained and the E2 table still has four rows.
alias_of: "${select.e1_best_run}"
dataset:
  synthetic:
    enabled: true
    p: ${select.e1_best_p}
    clean_ratio: 0.0
  real:
    enabled: false
eval:
  splits: [val, test]
keep_checkpoint: false
""".lstrip(),
        )
        continue
    write(
        f"e2_clean{c}",
        f"""
name: e2_clean{c}
family: e2
condition: synthetic
description: >
  Clean:noisy balance (spec E2) at the best p from E1, clean_ratio={c}.
  Tests whether identity pairs reduce over-correction (Koo et al.).
  0.33 is close to W&I's own share of already-correct sentences, which we
  measured at 33.8% of train_real.
dataset:
  synthetic:
    enabled: true
    p: ${{select.e1_best_p}}
    clean_ratio: {c}
  real:
    enabled: false
eval:
  splits: [val, test]
# true because e3_synthetic aliases the best E2 run, and both e3_synth2real's
# warm start and the Gradio demo load those weights.
keep_checkpoint: true
""".lstrip(),
    )

# --- E3: the main comparison ----------------------------------------------- #
write(
    "e3_synthetic",
    """
name: e3_synthetic
family: e3
condition: synthetic
description: >
  E3(a) synthetic-only at the best E2 configuration. This is the same training
  run as the winning E2 config, so run_experiments aliases it rather than
  retraining - one of the three savings that make the trimmed budget fit.
  NOTE: hyperparameters are still selected on the REAL val split, so
  "synthetic-only" means no real data in TRAINING, not no real data at all.
alias_of: "${select.e2_best_run}"
dataset:
  synthetic:
    enabled: true
    p: ${select.e1_best_p}
    clean_ratio: ${select.e2_best_clean_ratio}
  real:
    enabled: false
eval:
  splits: [val, test, indian]
keep_checkpoint: true
""".lstrip(),
)

write(
    "e3_real",
    """
name: e3_real
family: e3
condition: real
description: >
  E3(b) real-only: W&I train_real (32,308 sentences), which keeps W&I's own
  already-correct sentences (33.8% of the split).
dataset:
  synthetic:
    enabled: false
  real:
    enabled: true
eval:
  splits: [val, test, indian]
keep_checkpoint: true
""".lstrip(),
)

write(
    "e3_mixed",
    """
name: e3_mixed
family: e3
condition: mixed
description: >
  E3(c) mixed: real + synthetic, shuffled with the run seed. The realised
  ratio is NOT 50/50 (about 52% real at n=30000) and the stats file records
  the true proportion, which the report must state.
dataset:
  synthetic:
    enabled: true
    p: ${select.e1_best_p}
    clean_ratio: ${select.e2_best_clean_ratio}
  real:
    enabled: true
  shuffle: true
eval:
  splits: [val, test, indian]
keep_checkpoint: true
""".lstrip(),
)

write(
    "e3_synth2real",
    """
name: e3_synth2real
family: e3
condition: synth2real
description: >
  E3(d) synth->real: start from the trained e3_synthetic weights and fine-tune
  on real data. Warm-starting from the existing checkpoint rather than
  retraining stage 1 saves a full synthetic training run per seed.
dataset:
  synthetic:
    enabled: false
  real:
    enabled: true
stage2:
  enabled: true
  init_from: "e3_synthetic/seed{seed}"
  dataset: real
eval:
  splits: [val, test, indian]
keep_checkpoint: true
""".lstrip(),
)

# --- E4: distribution matching -------------------------------------------- #
write(
    "e4_synthetic_matched",
    """
name: e4_synthetic_matched
family: e4
condition: synthetic
description: >
  E4(a): synthetic-only with generator weights re-tuned to match the real
  error-type distribution of train_real (spec 7.1, after Wang et al. 2024).
dataset:
  synthetic:
    enabled: true
    p: ${select.e1_best_p}
    clean_ratio: ${select.e2_best_clean_ratio}
    weights_file: configs/experiments/e4_matched_weights.yaml
  real:
    enabled: false
eval:
  splits: [val, test, indian]
keep_checkpoint: true
""".lstrip(),
)

write(
    "e4_mixed_matched",
    """
name: e4_mixed_matched
family: e4
condition: mixed
description: >
  E4(c): mixed (real + distribution-matched synthetic). Compared against
  e3_mixed, this isolates the effect of matching the real error distribution.
dataset:
  synthetic:
    enabled: true
    p: ${select.e1_best_p}
    clean_ratio: ${select.e2_best_clean_ratio}
    weights_file: configs/experiments/e4_matched_weights.yaml
  real:
    enabled: true
  shuffle: true
eval:
  splits: [val, test, indian]
keep_checkpoint: true
""".lstrip(),
)

print(f"\ndone: {len(list(ROOT.glob('*.yaml')))} experiment configs")
